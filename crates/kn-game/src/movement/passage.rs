//! Проходимость клетки: знание о том, где можно стоять, приходит извне.

use super::grid::Cell;

/// Где существо может стоять.
///
/// Движок не знает ни форматов карты, ни объектов, ни специфики части серии:
/// поставщик (для K1 — `k1-data`, позже `k2-data`) отвечает на один вопрос про
/// клетку. Занятость чужими существами здесь ни при чём — она в
/// [`super::occupancy::Occupancy`].
pub trait Passage {
    /// Проходима ли клетка по данным поставщика.
    fn is_walkable(&self, cell: Cell) -> bool;
}
